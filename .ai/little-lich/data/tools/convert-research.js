// Converts the refined research and unit data (data/refined/) into the game's content files (littlelich/Data/).
// Research revamp, v0.1: Necromancy and Infusion only (Crypt Magic and Spider Sorcery stay disabled).
//
//   node .ai/little-lich/data/tools/convert-research.js
//
// Writes (overwrites):
//   littlelich/Data/research/necromancy.json, infusion.json  research nodes
//   littlelich/Data/research/tomes.json                      the two tomes
//   littlelich/Data/research/bench.json                      bench settings + level tiers from source/build.json
//   littlelich/Data/units/bases.json                         the 10 fighting bodies research unlocks
//   littlelich/Data/units/player_actions.json                one attack action per body
// Mappings: building "storage" -> "magical_storage"; resource "coin" -> "gold". Only fields the game reads are kept
// (the loader rejects unknown fields): review flags, legacy positions and notes stay in data/refined.
const fs = require('fs');
const path = require('path');

const dataDir = path.resolve(__dirname, '..');
const game = path.resolve(dataDir, '..', '..', '..', 'littlelich', 'Data');
const read = p => JSON.parse(fs.readFileSync(path.join(dataDir, p), 'utf8'));
const write = (p, header, value) => {
  const file = path.join(game, p);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, header.map(l => '// ' + l).join('\n') + '\n' + format(value) + '\n');
  console.log('wrote', path.relative(process.cwd(), file));
};

// One entry per line inside "entries" keeps the files diffable and readable.
function format(v) {
  if (v && Array.isArray(v.entries)) {
    const head = Object.entries(v).filter(([k]) => k !== 'entries').map(([k, x]) => `  ${JSON.stringify(k)}: ${JSON.stringify(x)},`);
    return ['{', ...head, '  "entries": [', v.entries.map(e => '    ' + JSON.stringify(e)).join(',\n'), '  ]', '}'].join('\n');
  }
  return JSON.stringify(v, null, 2);
}

const RESOURCE = { coin: 'gold' };
const BUILDING = { storage: 'magical_storage' };
const res = id => RESOURCE[id] ?? id;
const mapCost = c => Object.fromEntries(Object.entries(c || {}).map(([k, v]) => [res(k.toLowerCase()), v]));

// ---- Research ----
const TOMES = [
  { file: 'necromancy', id: 'necromancy', name: 'Necromancy', note: 'Starting tome', starts_owned: true, skill: 'necromancy' },
  { file: 'infusion', id: 'infusion', name: 'Infusion', note: 'Found at the Graveyard', found_by: { area_cleared: 'graveyard' }, skill: 'magic' },
];

const nodeOut = n => {
  const upgrade = n.kind === 'upgrade';
  const o = { id: n.id, name: n.name, tome: n.tome, description: n.description, requires: n.requires, kind: n.kind, work: n.work };
  if (upgrade) { o.max_level = n.max_level; o.work_growth_per_level = n.work_growth_per_level ?? 1.15; }
  if (n.time_multiplier && n.time_multiplier !== 1) o.time_multiplier = n.time_multiplier;
  o.layout = { x: n.layout.x, y: n.layout.y };
  if (n.icon) o.icon = n.icon;
  if (n.icon_large) o.icon_large = n.icon_large;
  o.effects = n.effects.map(e => {
    const x = { ...e };
    if (x.type === 'unlock' && x.kind === 'building') x.id = BUILDING[x.id] ?? x.id;
    if (x.type === 'modify' && x.per_level && !upgrade) delete x.per_level;
    return x;
  });
  o.placeholder = true;
  return o;
};

for (const t of TOMES) {
  const src = read(`refined/research/${t.file}.json`);
  write(`research/${t.file}.json`,
    [`${t.name} research (research revamp). Generated by .ai/little-lich/data/tools/convert-research.js from`,
      `data/refined/research/${t.file}.json; edit the refined file and re-run. work = research work; upgrade nodes cost`,
      'work x time_multiplier x work_growth_per_level ^ level. layout: x across, y = layer (roots at 0).'],
    { type: 'research_node', entries: src.nodes.map(nodeOut) });
}
write('research/tomes.json',
  ['Research tomes (research revamp, v0.1). Crypt Magic and Spider Sorcery are not loaded yet (placeholder decision).',
    'Necromancy is owned at the start; Infusion is found the first time the Graveyard is cleared (placeholder).'],
  { type: 'tome', entries: TOMES.map(({ file, ...t }) => ({ ...t, placeholder: true })) });

// ---- Bench (tiers from the old build.json; coin -> gold) ----
const build = read('source/build.json').ResearchBench;
write('research/bench.json',
  ['Research benches (research revamp). Placeholder formula:',
    'work per tick = (base_work + work_per_necromancer x staffed) x level_work_growth ^ (level - 1) x research efficiency.',
    'Bench level costs: level_tiers from the old build.json (ResearchBench), cost of level L = base x multiplier ^ (L - min_level),',
    'rounded to round_sig_figs significant figures, halves up. Extra benches and room come from research.'],
  [{
    type: 'research_bench', id: 'research_bench', name: 'Research bench',
    base_benches: 1, base_slots_per_bench: 2, base_work: 1, work_per_necromancer: 0.5, level_work_growth: 1.1,
    round_sig_figs: Number(String(build.Round).replace('sf', '')) || 2,
    level_tiers: build.Tiers.map(t => ({ min_level: t.MinLevel, max_level: t.MaxLevel, base: mapCost(t.Base), multiplier: mapCost(t.Multiplier) })),
    placeholder: true,
  }]);

// ---- Units: the fighting bodies research unlocks (the necromancer is a summon, see recipes/summoning.json) ----
const units = read('refined/units.json').units;
const unlockedBy = {};
for (const t of TOMES) for (const n of read(`refined/research/${t.file}.json`).nodes)
  for (const e of n.effects) if (e.type === 'unlock' && e.kind === 'unit') unlockedBy[e.id] = n.id;
const bodies = units.filter(u => u.can_fight && unlockedBy[u.id]);

const action = u => {
  const a = u.attack?.type ?? 'melee';
  const base = { type: 'battle_action', id: `${u.id}_attack`, name: `${u.name} attack`, cooldown_seconds: u.stats.spd, value: u.stats.atk };
  if (a === 'healer') return { ...base, effect: 'heal', target: 'ally_lowest', range: 'ranged' };
  // No area damage in battles yet: AOE attacks hit the front for now (placeholder).
  return { ...base, effect: 'damage', target: 'front', range: a === 'melee' ? 'melee' : 'ranged' };
};
write('units/player_actions.json',
  ['One attack per player body (research revamp), from data/refined/units.json: value = ATK, cooldown_seconds = SPD',
    '(taken as seconds between attacks, open decision). AOE attacks hit the front until battles have area damage.',
    'Generated by .ai/little-lich/data/tools/convert-research.js.'],
  { type: 'battle_action', entries: bodies.map(action).map(({ type, ...a }) => ({ ...a, placeholder: true })) });

const skeletonFamily = u => (u.tags || []).includes('skeleton');
write('units/bases.json',
  ['Player unit bodies (research revamp), from data/refined/units.json. Each is unlocked by the research node in',
    'unlock.research. Skeletons can carry a weapon and armour from the Unit Builder; wisps cannot. summon_required is a',
    'placeholder (the old data has no summon time). Barracks caps and slot spans are not used yet.',
    'Generated by .ai/little-lich/data/tools/convert-research.js.'],
  {
    type: 'undead',
    entries: bodies.map(u => ({
      id: u.id, name: u.name, side: 'player', role: u.attack?.type ?? 'melee', description: u.description,
      tags: u.tags || [], hp: u.stats.hp, actions: [`${u.id}_attack`], unlock: { research: unlockedBy[u.id] },
      weapon_slots: skeletonFamily(u) ? ['weapon'] : [], armour_slots: skeletonFamily(u) ? ['body'] : [],
      summon_cost: mapCost(u.summon_cost), summon_required: u.type === 'large' ? 10 : 5, placeholder: true,
    })),
  });

// Report what the game will not use yet, so nothing is lost silently.
const necro = units.find(u => u.id === 'necromancer');
console.log('necromancer summon cost (set in recipes/summoning.json):', JSON.stringify(mapCost(necro.summon_cost)));
console.log('bodies:', bodies.map(u => u.id).join(', '));
